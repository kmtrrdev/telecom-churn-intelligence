@app.post("/chat")
def chat_api(
    request: ChatRequest
):
    """
    Chatbot endpoint: takes a customer profile + the analysis result
    (from /analyze-customer) + a user question, and returns a natural
    language answer generated by a free LLM hosted on Hugging Face.
    """

    customer_df = pd.DataFrame(
        [request.customer.model_dump()]
    )

    analysis = analyze_customer(
        customer_df
    )

    answer = chat_about_customer(
        analysis=analysis,
        question=request.question,
        history=request.history
    )

    return {
        "answer": answer,
        "analysis": analysis
    }


# ============================================
# Chat-native endpoints (used by the static/ HTML+JS frontend)
# ============================================
# These carry the conversation entirely as JSON state round-tripped
# by the client (collected fields, last-asked fields, analysis
# result) instead of Streamlit's server-side session_state - the
# frontend is a static SPA, so all state lives in the browser and is
# sent back on every call.

class ExtractRequest(BaseModel):
    message: str
    asked_fields: List[str] = []
    collected: dict = {}


class ExtractResponse(BaseModel):
    reply: str
    collected: dict
    missing_fields: List[str]
    ready: bool


@app.post("/api/extract", response_model=ExtractResponse)
def extract_api(request: ExtractRequest):

    try:
        extracted = extract_customer_data(
            request.message, asked_fields=request.asked_fields
        )
    except RuntimeError as e:
        raise HTTPException(status_code=503, detail=str(e))

    if extracted.get("off_topic") and not any(
        extracted.get(f) is not None for f in REQUIRED_FIELDS
    ):
        asked = request.asked_fields
        hints = (
            "لسه محتاج:\n"
            + "\n".join(f"- **{f}** — {FIELD_HINTS_AR.get(f, f)}" for f in asked)
            if asked
            else "احكيلي عن العميل عشان نبدأ."
        )
        reply = (
            "أنا هنا عشان أساعدك تحلل عملاء التليكوم بس — أتوقع احتمال "
            "churn، أشرح السبب، أحسب الأثر المالي، وأقترح أفضل كامبين "
            "أو عرض. ممكن نكمل في بيانات العميل اللي كنا بنجمعها؟\n\n"
            + hints
        )
        return ExtractResponse(
            reply=reply,
            collected=request.collected,
            missing_fields=request.asked_fields,
            ready=False,
        )

    merged = merge_customer_data(request.collected, extracted)
    merged = apply_dataset_consistency_rules(merged)

    missing = get_missing_fields(merged)

    if missing:
        hints = "\n".join(
            f"- **{f}** — {FIELD_HINTS_AR.get(f, f)}" for f in missing
        )
        reply = (
            "تمام، سجّلت اللي قلته. لسه محتاج أعرف المعلومات دي عشان "
            "أقدر أحلل العميل صح:\n\n" + hints
        )
        return ExtractResponse(
            reply=reply, collected=merged, missing_fields=missing, ready=False
        )

    note = ""
    if merged.get("_total_charges_estimated"):
        note = (
            "\n\n_ملحوظة: TotalCharges اتحسبت تقريبيًا "
            "(MonthlyCharges × tenure) لأنك مقلتش الرقم الفعلي._"
        )

    reply = (
        "تمام، خلصت البيانات. جهّزت التحليل تحت 👇 وممكن تسألني أي حاجة "
        "عنه دلوقتي (زي: *ليه العميل ده هيسيب الخدمة؟* أو *ابعتله انهي "
        "كامبين؟*)." + note
    )

    return ExtractResponse(
        reply=reply, collected=merged, missing_fields=[], ready=True
    )


class AnalyzeFromCollectedRequest(BaseModel):
    collected: dict


@app.post("/api/analyze")
def analyze_from_collected_api(request: AnalyzeFromCollectedRequest):
    """
    Analyzes a single customer collected via the chat flow, and — since
    this is the "one customer at a time" entry point — automatically
    saves the customer into the master CSV dataset (data/customers_dataset.csv)
    so it also shows up in the CSV-upload dashboard / customer list.
    """

    payload = {k: request.collected[k] for k in REQUIRED_FIELDS}
    df = pd.DataFrame([payload])

    result = analyze_customer(df)

    saved = append_single_customer(payload)
    result["customer_id"] = saved["customerID"]
    result["saved_to_dataset"] = True

    return result


