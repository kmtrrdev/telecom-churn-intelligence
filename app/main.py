# ============================================
# Dataset / CSV batch endpoints
# ============================================
# "أكتر من عميل مرة واحدة" flow: upload a CSV of customers, analyze
# every row through the same engine as the chat flow, and roll the
# results up into dashboard KPIs. Uploaded rows can optionally be
# merged into the same master dataset (data/customers_dataset.csv)
# that single, chat-entered customers are saved into automatically.

REQUIRED_CSV_COLUMNS = set(FEATURE_COLUMNS)


def _read_csv_upload(raw: bytes) -> pd.DataFrame:
    try:
        df = pd.read_csv(io.BytesIO(raw))
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"تعذّرت قراءة الملف كـ CSV: {e}")

    df.columns = [c.strip() for c in df.columns]
    missing = REQUIRED_CSV_COLUMNS - set(df.columns)
    if missing:
        raise HTTPException(
            status_code=400,
            detail="الملف ناقصه الأعمدة دي: " + ", ".join(sorted(missing)),
        )
    if df.empty:
        raise HTTPException(status_code=400, detail="الملف فاضي.")

    # Raw CSV columns (esp. TotalCharges, which has blank values for
    # some tenure=0 customers) can load as strings instead of numbers.
    # Coerce them here so both analyze_dataframe() and upsert_customers()
    # see numeric types - otherwise every row fails analysis with a
    # str/int TypeError while still silently "saving" fine.
    df = coerce_numeric(df)
    return df


@app.post("/api/dataset/upload-csv")
def upload_csv_api(
    file: UploadFile = File(...),
    save_to_dataset: bool = Query(
        True, description="Merge uploaded rows into the master dataset"
    ),
):
    raw = file.file.read()
    df = _read_csv_upload(raw)

    batch = analyze_dataframe(df)
    dashboard = build_dashboard(batch["results"])
    save_current_upload(df)

    save_summary = None
    if save_to_dataset:
        save_summary = upsert_customers(df, source="csv_upload")

    return {
        "results": batch["results"],
        "errors": batch["errors"],
        "dashboard": dashboard,
        "rows_received": int(len(df)),
        "rows_analyzed": len(batch["results"]),
        "saved_to_dataset": save_summary,
    }


@app.delete("/api/dataset/current-upload")
def clear_current_upload_api():
    """Clear the active uploaded CSV so the dashboard/assistant go back
    to a clean "no file uploaded" state instead of showing stale data."""
    clear_current_upload()
    global _dashboard_cache
    _dashboard_cache = {"key": None, "value": None}
    return {"cleared": True}


_dashboard_cache = {"key": None, "value": None}


@app.get("/api/dataset/dashboard")
def dataset_dashboard_api(refresh: bool = Query(False)):
    """Dashboard for the CURRENT uploaded CSV only."""
    global _dashboard_cache
    cache_key = current_upload_signature()
    if cache_key == "empty":
        return {
            **build_dashboard([]),
            "dataset_stats": {"total_customers": 0, "source": "no_upload"},
            "has_current_upload": False,
        }

    if not refresh and _dashboard_cache["key"] == ("current", cache_key):
        return _dashboard_cache["value"]

    df = load_current_upload()
    batch = analyze_dataframe(df)
    dashboard = build_dashboard(batch["results"])
    dashboard["errors"] = batch["errors"]
    dashboard["dataset_stats"] = {
        "total_customers": int(len(df)),
        "source": "current_upload",
    }
    dashboard["has_current_upload"] = True
    dashboard["current_upload_signature"] = cache_key

    _dashboard_cache["key"] = ("current", cache_key)
    _dashboard_cache["value"] = dashboard
    return dashboard


class DatasetChatRequest(BaseModel):
    question: str
    history: List[ChatMessage] = []


@app.post("/api/dataset/chat")
def dataset_chat_api(request: DatasetChatRequest):
    df = load_current_upload()
    if df.empty:
        raise HTTPException(status_code=400, detail="ارفع ملف CSV أولًا عشان أقدر أتكلم معاك عنه.")

    batch = analyze_dataframe(df)
    context = build_dataset_chat_context(df, batch["results"])
    try:
        answer = chat_about_dataset(
            context=context,
            question=request.question,
            history=request.history,
        )
    except RuntimeError as e:
        raise HTTPException(status_code=503, detail=str(e))
    return {"answer": answer, "context_rows": int(len(df))}


@app.get("/api/dataset/customers")
def dataset_customers_api(
    search: str = Query("", description="Filter by customerID (substring)"),
    limit: int = Query(50, ge=1, le=500),
    offset: int = Query(0, ge=0),
):
    df = load_dataset()
    if search:
        df = df[df["customerID"].astype(str).str.contains(search, case=False, na=False)]

    total = int(len(df))
    page = df.iloc[offset: offset + limit]

    records = []
    for _, row in page.iterrows():
        rec = row.to_dict()
        try:
            payload = {k: rec[k] for k in FEATURE_COLUMNS if k in rec}
            analysis = analyze_customer(pd.DataFrame([payload]))
            rec["churn_probability"] = analysis["prediction"]["churn_probability"]
            rec["decision"] = analysis["prediction"]["decision"]
            rec["risk_band"] = analysis["prediction"]["risk_band"]
            rec["behavioral_segment"] = analysis["segmentation"]["behavioral_segment"]
            rec["value_risk_segment"] = analysis["segmentation"]["value_risk_segment"]
        except Exception:
            rec["churn_probability"] = 0.15
            rec["decision"] = "RETAIN"
            rec["risk_band"] = "Low Risk"
            rec["behavioral_segment"] = "Stable Low-Value"
            rec["value_risk_segment"] = "Low Value + Low Risk"
        records.append(rec)

    return {
        "total": total,
        "limit": limit,
        "offset": offset,
        "customers": records,
    }



# ============================================
# AI Sessions (Phase 6) — persistent chat sessions
# ============================================
# File-based store (app/sessions/session_store.py). "customer" and
# "dataset" sessions are kept in fully separate lists/state shapes,
# mirroring the independent pipelines above. The frontend owns *when*
# to save (e.g. after each turn) — these endpoints are plain CRUD.

class SessionCreateRequest(BaseModel):
    kind: str  # "customer" | "dataset"
    title: str = ""
    state: dict = {}


class SessionUpdateRequest(BaseModel):
    title: Optional[str] = None
    pinned: Optional[bool] = None
    state: Optional[dict] = None


def _validate_kind(kind: str):
    if kind not in ("customer", "dataset"):
        raise HTTPException(status_code=400, detail="kind لازم يكون customer أو dataset")


@app.get("/api/sessions")
def sessions_list_api(kind: Optional[str] = Query(None), search: str = Query("")):
    if kind:
        _validate_kind(kind)
    return {"sessions": list_sessions(kind=kind, search=search)}


@app.post("/api/sessions")
def sessions_create_api(request: SessionCreateRequest):
    _validate_kind(request.kind)
    return create_session(request.kind, title=request.title, state=request.state)


@app.get("/api/sessions/{session_id}")
def sessions_get_api(session_id: str):
    record = get_session(session_id)
    if record is None:
        raise HTTPException(status_code=404, detail="الجلسة دي مش موجودة.")
    return record


@app.patch("/api/sessions/{session_id}")
def sessions_update_api(session_id: str, request: SessionUpdateRequest):
    record = update_session(
        session_id, title=request.title, pinned=request.pinned, state=request.state
    )
    if record is None:
        raise HTTPException(status_code=404, detail="الجلسة دي مش موجودة.")
    return record


@app.delete("/api/sessions/{session_id}")
def sessions_delete_api(session_id: str):
    if not delete_session(session_id):
        raise HTTPException(status_code=404, detail="الجلسة دي مش موجودة.")
    return {"status": "deleted", "id": session_id}


@app.get("/api/dataset/customer/{customer_id}")
def dataset_customer_detail_api(customer_id: str):
    # Dashboard/customer details are anchored to the CURRENT upload first.
    current = load_current_upload()
    match = current[current["customerID"].astype(str) == str(customer_id)]
    if not match.empty:
        row = match.iloc[0].to_dict()
    else:
        row = get_customer_row(customer_id)

    if row is None:
        raise HTTPException(status_code=404, detail="العميل ده مش موجود في الداتاست.")

    payload = {k: row[k] for k in FEATURE_COLUMNS}
    df = pd.DataFrame([payload])
    result = analyze_customer(df)
    result["customer_id"] = row["customerID"]
    return result
